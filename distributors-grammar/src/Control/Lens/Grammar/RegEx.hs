instance Lexical token => TerminalSymbol token (RegEx token) where
  terminal = foldl (\acc t -> acc <> token t) mempty
instance NonTerminalSymbol (RegEx token) where
  nonTerminal = NonTerminal
instance Lexical token => Tokenized token (RegEx token) where
  tokenClass = RegExam
instance Lexical token => Monoid (RegEx token) where
  mempty = SeqEmpty
-- | Sequences are associative, as items normalized by `sequenced`.
instance Lexical token => Semigroup (RegEx token) where
  rex0 <> rex1 = sequenced (items rex0 <> items rex1)
-- | Alternatives are associative, as normalized by `alternated`.
instance Lexical token => DisjunctiveMonoid (RegEx token) where
  falseP = RegExam falseP
  rex0 >|< rex1 = alternated (alternatives rex0 <> alternatives rex1)
instance Lexical token => KleeneStarAlgebra (RegEx token) where
  optK (RegExam cls) | cls == falseP = mempty
  optK SeqEmpty = mempty
  optK (KleenePlus rex) = starK rex
  optK rex@(KleeneStar _) = rex
  optK rex@(KleeneOpt _) = rex
  optK rex = KleeneOpt rex
  starK (RegExam cls) | cls == falseP = mempty
  starK SeqEmpty = mempty
  starK rex = KleeneStar rex
  plusK (RegExam cls) | cls == falseP = falseP
  plusK SeqEmpty = mempty
  plusK rex = KleenePlus rex
  timesK lo0 hi rex = case (max 0 lo0, hi) of
    (lo, Just m) | lo > m -> falseP
    _ | SeqEmpty <- rex -> mempty
    (lo, _) | RegExam cls <- rex, cls == falseP ->
      if lo == 0 then mempty else falseP
    (0, Nothing) -> starK rex
    (1, Nothing) -> plusK rex
    (_, Just 0) -> mempty
    (0, Just 1) -> optK rex
    (1, Just 1) -> rex
    (lo, _) -> KleeneTimes lo hi rex
instance (Lexical token, HasTrie token, HasTrie (TokenClass token))
  => HasTrie (RegEx token) where
    data (RegEx token :->: b) = RegExTrie
      { seqEmptyTrie :: b
      , nonTerminalTrie :: String :->: b
      , sequenceTrie :: [RegEx token] :->: b
      , alternateTrie :: [RegEx token] :->: b
      , kleeneStarTrie :: RegEx token :->: b
      , kleeneOptTrie :: RegEx token :->: b
      , kleenePlusTrie :: RegEx token :->: b
      , kleeneTimesTrie :: ((Int, Maybe Int), RegEx token) :->: b
      , backtrackingTrie :: RegEx token :->: b
      , classTrie :: TokenClass token :->: b
      }
    trie f = RegExTrie
      { seqEmptyTrie = f mempty
      , nonTerminalTrie = trie (f . nonTerminal)
      , sequenceTrie = trie (f . mconcat)
      , alternateTrie = trie (f . foldr (>|<) falseP)
      , kleeneStarTrie = trie (f . starK)
      , kleeneOptTrie = trie (f . optK)
      , kleenePlusTrie = trie (f . plusK)
      , kleeneTimesTrie = trie (f . \((lo, hi), x) -> timesK lo hi x)
      , backtrackingTrie = trie (f . try)
      , classTrie = trie (f . RegExam)
      }
    untrie rex = \case
      SeqEmpty -> seqEmptyTrie rex
      NonTerminal name -> untrie (nonTerminalTrie rex) name
      Sequence x y zs -> untrie (sequenceTrie rex) (x : y : zs)
      KleeneStar x -> untrie (kleeneStarTrie rex) x
      KleenePlus x -> untrie (kleenePlusTrie rex) x
      KleeneOpt x -> untrie (kleeneOptTrie rex) x
      KleeneTimes lo hi x -> untrie (kleeneTimesTrie rex) ((lo, hi), x)
      Backtracking x -> untrie (backtrackingTrie rex) x
      RegExam cls -> untrie (classTrie rex) cls
      Alternate x y zs -> untrie (alternateTrie rex) (x : y : zs)
    enumerate rex = mconcat
      [ [(SeqEmpty, seqEmptyTrie rex)]
      , first' NonTerminal <$> enumerate (nonTerminalTrie rex)
      , first' mconcat <$> enumerate (sequenceTrie rex)
      , first' (foldr (>|<) falseP) <$> enumerate (alternateTrie rex)
      , first' KleeneStar <$> enumerate (kleeneStarTrie rex)
      , first' KleeneOpt <$> enumerate (kleeneOptTrie rex)
      , first' KleenePlus <$> enumerate (kleenePlusTrie rex)
      , first' (\((lo, hi), x) -> KleeneTimes lo hi x)
          <$> enumerate (kleeneTimesTrie rex)
      , first' Backtracking <$> enumerate (backtrackingTrie rex)
      , first' RegExam <$> enumerate (classTrie rex)
      ]

-- | The items of a sequence.
items :: RegEx token -> [RegEx token]
items = \case
  SeqEmpty -> []
  Sequence rex0 rex1 rexes -> rex0 : rex1 : rexes
  rex -> [rex]

{- | Items, normalized: any which fails fails, & runs of a repeated item,
@b@, whose items are @B@, are rewritten until none apply, by

* @B b*@ & @b* B@ to @b+@,
* @b* b*@ to @b*@, & @b+ b*@ & @b* b+@ to @b+@,
* @b+ B@ to @B b+@, & @b+ b+@ to @B b+@,

so that sequences of sequences are associative.
-}
sequenced :: Lexical token => [RegEx token] -> RegEx token
sequenced rexes
  | any isFail rexes = falseP
  | otherwise = case rewrite rexes of
      [] -> SeqEmpty
      [rex] -> rex
      rex0 : rex1 : rexes' -> Sequence rex0 rex1 rexes'
  where
    isFail = \case
      RegExam cls -> cls == falseP
      _ -> False
    rewrite xs = maybe xs rewrite (step xs)
    step = \case
      [] -> Nothing
      xs@(x : rest) -> case once xs of
        Just xs' -> Just xs'
        Nothing -> (x :) <$> step rest
    -- a rule applying at the start of the items
    once = \case
      KleeneStar b : KleeneStar b' : rest | b == b' ->
        Just (KleeneStar b : rest)
      KleenePlus b : KleeneStar b' : rest | b == b' ->
        Just (KleenePlus b : rest)
      KleeneStar b : KleenePlus b' : rest | b == b' ->
        Just (KleenePlus b : rest)
      KleenePlus b : KleenePlus b' : rest | b == b' ->
        Just (items b <> (KleenePlus b : rest))
      KleeneStar b : rest | not (null (items b))
        , Just rest' <- after (items b) rest ->
        Just (KleenePlus b : rest')
      KleenePlus b : rest | not (null (items b))
        , Just rest' <- after (items b) rest ->
        Just (items b <> (KleenePlus b : rest'))
      xs | Just (b, rest) <- starred xs -> Just (KleenePlus b : rest)
      _ -> Nothing
    -- the rest of the items after a prefix of them
    after prefix xs
      | prefix == take (length prefix) xs = Just (drop (length prefix) xs)
      | otherwise = Nothing
    -- items which a repetition of them follows
    starred xs = case [ (b, rest)
      | n <- [1 .. length xs - 1]
      , KleeneStar b : rest <- [drop n xs]
      , items b == take n xs
      ] of
      found : _ -> Just found
      [] -> Nothing

-- | The alternatives of an alternation, with the empty word for an option.
alternatives :: Lexical token => RegEx token -> [RegEx token]
alternatives = \case
  RegExam cls | cls == falseP -> []
  Alternate rex0 rex1 rexes -> rex0 : rex1 : rexes
  KleeneOpt rex -> alternatives rex <> [SeqEmpty]
  KleeneStar rex -> [KleenePlus rex, SeqEmpty]
  rex -> [rex]

{- | Alternatives, normalized: those of tokens are one t'TokenClass',
in place of the first, the empty word makes them optional,
& each is kept once, in order, so that alternatives of alternatives
are associative.
-}
alternated :: Lexical token => [RegEx token] -> RegEx token
alternated rexes =
  (if SeqEmpty `elem` rexes then optK else id) $
    case nub (unionTokens [rex | rex <- rexes, rex /= SeqEmpty]) of
      [] -> falseP
      [rex] -> rex
      rex0 : rex1 : rexes' -> Alternate rex0 rex1 rexes'
  where
    unionTokens xs = case [cls | x <- xs, Just cls <- [tokenOf x]] of
      [] -> xs
      classes ->
        placeFirst (alternatives (tokenClass (foldr1 (>|<) classes))) xs
    placeFirst union = \case
      x : rest | Just _ <- tokenOf x ->
        union <> [y | y <- rest, Nothing <- [tokenOf y]]
      x : rest -> x : placeFirst union rest
      [] -> []
    tokenOf = \case
      RegExam cls -> Just cls
      _ -> Nothing

{- | A t'Bnf' consists of a distinguished starting rule
and a set of named rules. When a t'Bnf' supports `NonTerminalSymbol`s,
then it supports the `BackusNaurForm` interface
by replacing recursive calls with `nonTerminal`s.

> prop> ruleRec label f = rule label (f (nonTerminal label))

-}
data Bnf rule = Bnf
  { startBnf :: rule
  , rulesBnf :: Set (String, rule)
  } deriving stock (Eq, Ord, Show, Read)

{- | Lift a rule to a t'Bnf'. -}
liftBnf0 :: Ord a => a -> Bnf a
liftBnf0 a = Bnf a mempty

{- | Lift a function of rules to t'Bnf's. -}
liftBnf1 :: (Coercible a b, Ord b) => (a -> b) -> Bnf a -> Bnf b
liftBnf1 f (Bnf start rules) = Bnf (f start) (Set.map coerce rules)

{- | Lift a binary function of rules to t'Bnf's. -}
liftBnf2
  :: (Coercible a c, Coercible b c, Ord c)
  => (a -> b -> c) -> Bnf a -> Bnf b -> Bnf c
liftBnf2 f (Bnf start0 rules0) (Bnf start1 rules1) =
  Bnf (f start0 start1) (Set.map coerce rules0 <> Set.map coerce rules1)

{- |
The [Brzozowski derivative]
(https://dl.acm.org/doi/pdf/10.1145/321239.321249) of a
`RegEx`tended t'Bnf', with memoization.

> prop> word =~ diffB prefix pattern = prefix <> word =~ pattern

Unfortunately, despite elegance & optimization, Brzozowski's
pattern matching algorithm is worst case exponential in grammar size.
See Might, Darais & Spiewak, [Parsing With Derivatives]
(https://matt.might.net/papers/might2011derivatives.pdf).
-}
diffB
  :: (Lexical token, HasTrie token, HasTrie (TokenClass token))
  => [token] -> Bnf (RegEx token) -> Bnf (RegEx token)
diffB prefix (Bnf start rules) =
  Bnf (foldl' (flip diff1B) start prefix) rules
  where
    -- derivative wrt 1 token, memoized
    diff1B = memo2 $ \x -> \case
      SeqEmpty -> falseP
      NonTerminal nameY -> anyP (diff1B x) (rulesNamed nameY rules)
      Sequence y1 y ys ->
        if δ (Bnf y1 rules) then y1'y2 >|< y1y2' else y1'y2
        where
          y2 = mconcat (y : ys)
          y1'y2 = diff1B x y1 <> y2
          y1y2' = y1 <> diff1B x y2
      KleeneStar y -> diff1B x y <> starK y
      KleeneOpt y -> diff1B x y
      Backtracking y -> diff1B x y
      KleenePlus y -> diff1B x y <> starK y
      KleeneTimes lo hi y ->
        diff1B x y <> timesK (lo - 1) (subtract 1 <$> hi) y
      RegExam cls -> if tokenClass cls x then mempty else falseP
      Alternate y1 y2 ys -> anyP (diff1B x) (y1 : y2 : ys)

-- | Does a pattern match the empty word?
δ :: (Lexical token, HasTrie token, HasTrie (TokenClass token))
  => Bnf (RegEx token) -> Bool
δ (Bnf start rules) = ν start where
  ν = memo $ \case
    SeqEmpty -> True
    KleeneStar _ -> True
    KleeneOpt _ -> True
    Backtracking y -> ν y
    KleenePlus y -> ν y
    KleeneTimes lo _ y -> lo == 0 || ν y
    Sequence y1 y2 ys -> all ν (y1 : y2 : ys)
    Alternate y1 y2 ys -> any ν (y1 : y2 : ys)
    NonTerminal nameY -> any ν (rulesNamed nameY rules)
    _ -> False

rulesNamed :: Ord rule => String -> Set (String, rule) -> Set rule
rulesNamed nameX = foldl' (flip inserter) Set.empty where
  inserter (nameY,y) =
    if nameX == nameY then Set.insert y else id

-- Bnf instances
instance (Ord rule, NonTerminalSymbol rule) => Ruled (Bnf rule) where
  rule label (Bnf newRule oldRules) = (nonTerminal label)
    {rulesBnf = Set.insert (label, newRule) oldRules}
instance (Ord rule, NonTerminalSymbol rule)
  => BackusNaurForm (Bnf rule) where
    ruleRec label f = rule label (f (nonTerminal label))
-- | `try` the start of a t'Bnf', recording it as its rules do.
instance Tried rule => Tried (Bnf rule) where
  try (Bnf start rules) = Bnf (try start) rules
-- | A `RegEx` records `try`, but for patterns of the empty word
-- or none, which can't fail after reading a token.
instance Lexical token => Tried (RegEx token) where
  try rex = case rex of
    Backtracking _ -> rex
    SeqEmpty -> rex
    RegExam cls | cls == falseP -> rex
    _ -> Backtracking rex
instance (Ord rule, TerminalSymbol token rule)
  => TerminalSymbol token (Bnf rule) where
  terminal = liftBnf0 . terminal
instance (Ord rule, NonTerminalSymbol rule)
  => NonTerminalSymbol (Bnf rule) where
  nonTerminal = liftBnf0 . nonTerminal
instance (Ord rule, Tokenized token rule)
  => Tokenized token (Bnf rule) where
  tokenAny = liftBnf0 tokenAny
  token = liftBnf0 . token
  oneOf = liftBnf0 . oneOf
  notOneOf = liftBnf0 . notOneOf
  asIn = liftBnf0 . asIn
  notAsIn = liftBnf0 . notAsIn
  tokenRange lo = liftBnf0 . tokenRange lo
  tokenClass = liftBnf0 . tokenClass
instance (Ord rule, KleeneStarAlgebra rule)
  => KleeneStarAlgebra (Bnf rule) where
  starK = liftBnf1 starK
  plusK = liftBnf1 plusK
  optK = liftBnf1 optK
instance (Ord rule, DisjunctiveMonoid rule)
  => DisjunctiveMonoid (Bnf rule) where
  falseP = liftBnf0 falseP
  (>|<) = liftBnf2 (>|<)
instance (Ord rule, Monoid rule) => Monoid (Bnf rule) where
  mempty = liftBnf0 mempty
instance (Ord rule, Semigroup rule) => Semigroup (Bnf rule) where
  (<>) = liftBnf2 (<>)


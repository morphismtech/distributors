{- | `Lexical` tokens have kinds, telling their lexical roles, like
an identifier's or a keyword's, or a character's `GeneralCategory`,
& a `BooleanAlgebra` of tests of them, `TokenTest`s, generated by tests
of which tokens they are, of which kinds they are, & of which ranges
they're in, where they're enumerable.

>>> tokenKind 'a'
LowercaseLetter

Each test has one form, so that `TokenTest`s are equal just when they
test alike, & `tokenTest` is a homomorphism of `BooleanAlgebra`s.

> prop> tokenTest trueP = const True
> prop> tokenTest (notP x) = not . tokenTest x
> prop> tokenTest (x >|< y) t = tokenTest x t || tokenTest y t
> prop> tokenTest (x >&< y) t = tokenTest x t && tokenTest y t
> prop> tokenTest (testOneOf ts) = (`elem` ts)
> prop> tokenTest (testKinds (TokenKinds ks)) = (`Set.member` ks) . tokenKind
> prop> tokenTest (testRange lo hi) t = lo <= t && t <= hi
-}
class
  ( Ord token
  , Ord (TokenKind token), Enum (TokenKind token), Bounded (TokenKind token)
  , BooleanAlgebra (TokenTest token), Ord (TokenTest token)
  ) => Lexical token where

  {- | The kinds of tokens, none but @()@ by default. -}
  type TokenKind token
  type TokenKind token = ()
  {- | A token's kind. -}
  tokenKind :: token -> TokenKind token
  default tokenKind :: TokenKind token ~ () => token -> TokenKind token
  tokenKind _ = ()

  {- | The tests of tokens, `Cofinite` sets of them by default. -}
  type TokenTest token
  type TokenTest token = Cofinite token
  {- | Does a token pass a test? -}
  tokenTest :: TokenTest token -> token -> Bool
  default tokenTest
    :: TokenTest token ~ Cofinite token => TokenTest token -> token -> Bool
  tokenTest = flip cofiniteMember
  {- | The test of being one of some tokens. -}
  testOneOf :: [token] -> TokenTest token
  default testOneOf
    :: TokenTest token ~ Cofinite token => [token] -> TokenTest token
  testOneOf = Finite . Set.fromList
  {- | The test of being of one of some kinds. -}
  testKinds :: TokenKinds (TokenKind token) -> TokenTest token
  default testKinds
    :: (TokenTest token ~ Cofinite token, TokenKind token ~ ())
    => TokenKinds (TokenKind token) -> TokenTest token
  testKinds = kindless
  {- | The test of being between two tokens, inclusive, by their
  enumeration, for tokens whose `Enum` & `Ord` agree. -}
  testRange :: Enum token => token -> token -> TokenTest token
  testRange lo hi = testOneOf [lo .. hi]
  {- | The tokens which pass a test, by their number & their index,
  where they're finitely many & listable, so that generators sample them
  uniformly, rather than by rejection. -}
  testFinite :: TokenTest token -> Maybe (Int, Int -> token)
  default testFinite
    :: TokenTest token ~ Cofinite token
    => TokenTest token -> Maybe (Int, Int -> token)
  testFinite = \case
    Finite ts -> Just (Set.size ts, (`Set.elemAt` ts))
    Cofinite _ -> Nothing

instance Lexical Char where
  type TokenKind Char = GeneralCategory
  tokenKind = generalCategory
  type TokenTest Char = TokenRanges Char
  tokenTest = flip rangesMember
  testOneOf = Exts.fromList
  testKinds (TokenKinds cats) = foldr ((>|<) . categoryRanges) falseP cats
  testRange = rangesBetween
  testFinite = rangesFinite
instance Lexical Word8 where
  type TokenTest Word8 = TokenRanges Word8
  tokenTest = flip rangesMember
  testOneOf = Exts.fromList
  testKinds = kindless
  testRange = rangesBetween
  testFinite = rangesFinite
instance Lexical () where
  type TokenTest () = TokenRanges ()
  tokenTest = flip rangesMember
  testOneOf = Exts.fromList
  testKinds = kindless
  testRange = rangesBetween
  testFinite = rangesFinite

-- | Tests of kinds, where there are none but @()@.
kindless :: BooleanAlgebra test => TokenKinds () -> test
kindless (TokenKinds ks) = if Set.null ks then falseP else trueP

{- | A class of tokens, by their `TokenTest`, a `Tokenized`
`BooleanAlgebra`, such that the following hold.

> prop> trueP = tokenAny
> prop> falseP = oneOf []
> prop> notP . oneOf = notOneOf
> prop> notP . asIn = notAsIn
-}
newtype TokenClass token = TokenClass {classTest :: TokenTest token}
deriving newtype instance Lexical token => Eq (TokenClass token)
deriving newtype instance Lexical token => Ord (TokenClass token)
deriving newtype instance Lexical token => DisjunctiveMonoid (TokenClass token)
deriving newtype instance Lexical token => BooleanAlgebra (TokenClass token)
deriving newtype instance Show (TokenTest token) => Show (TokenClass token)
deriving newtype instance Read (TokenTest token) => Read (TokenClass token)
instance Lexical token => Tokenized token (TokenClass token) where
  tokenClass = id

{- | `Tokenized` combinators for constructing lexical tokens,
each a `tokenClass` by default.

> prop> tokenAny = tokenClass trueP
> prop> token t = tokenClass (oneOf [t])

When a `Tokenized` is a `DisjunctiveMonoid`, then
`tokenClass` is expected to act homomorphically on disjunction.

> prop> falseP = tokenClass falseP
> prop> tokenClass x >|< tokenClass y = tokenClass (x >|< y)
-}
class Lexical token => Tokenized token p | p -> token where
  {-# MINIMAL tokenAny | tokenClass #-}

  {- | A single token of a class. -}
  tokenClass :: TokenClass token -> p
  default tokenClass
    :: (p ~ q token token, Choice q, Cochoice q)
    => TokenClass token -> p
  tokenClass (TokenClass test) = satisfy (tokenTest test)

  {- | Any single token. -}
  tokenAny :: p
  tokenAny = tokenClass trueP

  {- | A single specified `token`. -}
  token :: token -> p
  token t = tokenClass (TokenClass (testOneOf [t]))

  {- | A single token which is `oneOf` a set.

  > prop> token x = oneOf [x]
  -}
  oneOf :: Foldable f => f token -> p
  oneOf = tokenClass . TokenClass . testOneOf . toList

  {- | A single token which is `notOneOf` a set.

  > prop> tokenAny = notOneOf []
  -}
  notOneOf :: Foldable f => f token -> p
  notOneOf = tokenClass . TokenClass . notP . testOneOf . toList

  {- | A single token which is `asIn` a kind. -}
  asIn :: TokenKind token -> p
  asIn kind = tokenClass (TokenClass (testKinds @token (TokenKinds (Set.singleton kind))))

  {- | A single token which is `notAsIn` a kind. -}
  notAsIn :: TokenKind token -> p
  notAsIn kind =
    tokenClass (TokenClass (notP (testKinds @token (TokenKinds (Set.singleton kind)))))

  {- | A single token between two, inclusive, by their enumeration,
  for tokens whose `Enum` & `Ord` agree.

  > prop> tokenRange lo hi = oneOf [lo .. hi]
  -}
  tokenRange :: Enum token => token -> token -> p
  tokenRange lo hi = tokenClass (TokenClass (testRange lo hi))

{- | A single token that satisfies a predicate. -}
satisfy
  :: (Tokenized a (p a a), Choice p, Cochoice p)
  => (a -> Bool) -> p a a
satisfy f = satisfied f >?< tokenAny

{- | A specified stream of `tokens`. -}
tokens
  :: ( Foldable f, Tokenized a (p a a)
     , Monoidal p, Choice p
     , AsEmpty s, Cons s s a a
     )
  => f a -> p s s
tokens = foldr ((>:<) . token) asEmpty

-- instances
instance Lexical token => Tokenized token (token -> Bool) where
  tokenClass (TokenClass test) = tokenTest test
  tokenAny _ = True
  token = (==)
  asIn = lmap tokenKind . (==)
  notAsIn = lmap tokenKind . (/=)
  tokenRange lo hi x = lo <= x && x <= hi
deriving via (token -> Bool) instance Lexical token
  => Tokenized token (Predicate token)
instance Tokenized token (f token)
  => Tokenized token (Joker f token token) where
    tokenClass = Joker . tokenClass @token
    tokenAny = Joker (tokenAny @token)
    token = Joker . token @token
    oneOf = Joker . oneOf @token
    notOneOf = Joker . notOneOf @token
    asIn = Joker . asIn @token
    notAsIn = Joker . notAsIn @token
    tokenRange lo hi = Joker (tokenRange @token lo hi)
instance Tokenized Char (ReadP Char) where
  tokenClass = ReadP.satisfy . tokenClass
  tokenAny = ReadP.get
  token = ReadP.char
instance Tokenized Char (ReadPrec Char) where
  tokenClass = ReadPrec.lift . tokenClass
  tokenAny = ReadPrec.lift tokenAny
  token = ReadPrec.lift . token
instance (Lexical token, Arbitrary token) => Tokenized token (Gen token) where
  -- finitely many tokens are sampled uniformly, & others by rejection
  tokenClass (TokenClass test) = case testFinite test of
    Just (n, nth) | n > 0 -> nth <$> Gen.chooseInt (0, n - 1)
    _ -> arbitrary `Gen.suchThat` tokenTest test
  tokenAny = arbitrary @token
  token = pure
instance (RandomGen g, Monad m, Lexical token, Random token)
  => Tokenized token (StateT g m token) where
  tokenClass (TokenClass test) = case testFinite test of
    Just (n, nth) | n > 0 -> nth <$> state (randomR (0, n - 1))
    _ -> iterateUntil (tokenTest test) tokenAny
  tokenAny = state random
  token = pure

{- | Tests of kinds, any set of them, a `BooleanAlgebra` of bounded,
enumerable kinds, complementing within all of them. -}
newtype TokenKinds kind = TokenKinds (Set kind)
  deriving stock (Eq, Ord, Show, Read)
instance Ord kind => DisjunctiveMonoid (TokenKinds kind) where
  falseP = TokenKinds Set.empty
  TokenKinds xs >|< TokenKinds ys = TokenKinds (Set.union xs ys)
instance (Ord kind, Enum kind, Bounded kind)
  => BooleanAlgebra (TokenKinds kind) where
    trueP = TokenKinds (Set.fromList [minBound .. maxBound])
    notP (TokenKinds xs) = TokenKinds (Set.fromList [minBound .. maxBound] Set.\\ xs)
    TokenKinds xs >&< TokenKinds ys = TokenKinds (Set.intersection xs ys)

{- | Tests of enumerable tokens, by their disjoint ranges, of
[range-set-list](https://hackage.haskell.org/package/range-set-list),
a `BooleanAlgebra` of bounded tokens, each test having one form.
They `Show` & `Read` by their ranges' list.
-}
newtype TokenRanges token = TokenRanges (RSet token)
  deriving newtype (Eq, Ord)
instance (Ord token, Enum token) => IsList (TokenRanges token) where
  type Item (TokenRanges token) = token
  fromList = TokenRanges . RSet.fromList
  toList (TokenRanges xs) = RSet.toList xs
instance AsEmpty (TokenRanges token) where
  _Empty = nearly (TokenRanges RSet.empty) (\(TokenRanges xs) -> RSet.null xs)
instance (Ord token, Enum token) => DisjunctiveMonoid (TokenRanges token) where
  falseP = TokenRanges RSet.empty
  TokenRanges xs >|< TokenRanges ys = TokenRanges (RSet.union xs ys)
instance (Ord token, Enum token, Bounded token)
  => BooleanAlgebra (TokenRanges token) where
    trueP = TokenRanges RSet.full
    notP (TokenRanges xs) = TokenRanges (RSet.complement xs)
    TokenRanges xs >&< TokenRanges ys = TokenRanges (RSet.intersection xs ys)
instance (Ord token, Enum token, Show token) => Show (TokenRanges token) where
  showsPrec d (TokenRanges xs) = showParen (d > 10) $
    showString "fromRangeList " . shows (RSet.toRangeList xs)
instance (Ord token, Enum token, Read token) => Read (TokenRanges token) where
  readPrec = Read.parens $ ReadPrec.prec 10 $ do
    Read.Ident "fromRangeList" <- Read.lexP
    TokenRanges . RSet.fromRangeList <$> ReadPrec.step readPrec

rangesMember :: Ord token => token -> TokenRanges token -> Bool
rangesMember x (TokenRanges xs) = RSet.member x xs

rangesBetween :: Ord token => token -> token -> TokenRanges token
rangesBetween lo hi
  | lo > hi = TokenRanges RSet.empty
  | otherwise = TokenRanges (RSet.singletonRange (lo, hi))

-- | The tokens of ranges, by their number & index, listing the ranges.
rangesFinite :: Enum token => TokenRanges token -> Maybe (Int, Int -> token)
rangesFinite (TokenRanges xs) = Just (sum (map size runs), nth runs)
  where
    runs = RSet.toRangeList xs
    size (lo, hi) = fromEnum hi - fromEnum lo + 1
    nth ((lo, hi) : rest) i
      | i < size (lo, hi) = toEnum (fromEnum lo + i)
      | otherwise = nth rest (i - size (lo, hi))
    nth [] _ = error "rangesFinite: out of range"

-- | Each `GeneralCategory`'s characters, by their ranges, computed once.
categoryRanges :: GeneralCategory -> TokenRanges Char
categoryRanges cat = Map.findWithDefault falseP cat categoryTable

categoryTable :: Map GeneralCategory (TokenRanges Char)
categoryTable = Map.fromListWith (>|<)
  [ (generalCategory lo, TokenRanges (RSet.singletonRange (lo, hi)))
  | (lo, hi) <- runs minBound ]
  where
    runs lo =
      let
        cat = generalCategory lo
        hi = last' lo (takeWhile ((== cat) . generalCategory) [succ' lo ..])
      in (lo, hi) : if hi == maxBound then [] else runs (succ hi)
    succ' c = if c == maxBound then c else succ c
    last' x = \case
      [] -> x
      ys -> last ys

{- | Tests of tokens, by finite sets of them, or their complements,
a `BooleanAlgebra` each test having one form, where tokens are
infinitely many; for finitely many, `TokenRanges` are. -}
data Cofinite token = Finite (Set token) | Cofinite (Set token)
  deriving stock (Eq, Ord, Show, Read)
instance Ord token => DisjunctiveMonoid (Cofinite token) where
  falseP = Finite Set.empty
  Finite xs >|< Finite ys = Finite (Set.union xs ys)
  Finite xs >|< Cofinite ys = Cofinite (ys Set.\\ xs)
  Cofinite xs >|< Finite ys = Cofinite (xs Set.\\ ys)
  Cofinite xs >|< Cofinite ys = Cofinite (Set.intersection xs ys)
instance Ord token => BooleanAlgebra (Cofinite token) where
  trueP = Cofinite Set.empty
  notP = \case
    Finite xs -> Cofinite xs
    Cofinite xs -> Finite xs
  Finite xs >&< Finite ys = Finite (Set.intersection xs ys)
  Finite xs >&< Cofinite ys = Finite (xs Set.\\ ys)
  Cofinite xs >&< Finite ys = Finite (ys Set.\\ xs)
  Cofinite xs >&< Cofinite ys = Cofinite (Set.union xs ys)

cofiniteMember :: Ord token => token -> Cofinite token -> Bool
cofiniteMember x = \case
  Finite xs -> Set.member x xs
  Cofinite xs -> Set.notMember x xs

{- | Tests of tokens tagged by their kinds, as a test of their tags
for each kind, a `BooleanAlgebra` of tests, pointwise, each test having
one form, where each kind's has, omitting kinds which `falseP` tests. -}
newtype ByKind kind test = ByKind (Map kind test)
  deriving stock (Eq, Ord, Show, Read)
instance (Ord kind, DisjunctiveMonoid test)
  => DisjunctiveMonoid (ByKind kind test) where
    falseP = ByKind Map.empty
    ByKind xs >|< ByKind ys = ByKind (Map.unionWith (>|<) xs ys)
instance (Ord kind, Enum kind, Bounded kind, BooleanAlgebra test, Eq test)
  => BooleanAlgebra (ByKind kind test) where
    trueP = ByKind (Map.fromList [(k, trueP) | k <- [minBound .. maxBound]])
    notP (ByKind xs) = ByKind $ Map.fromList
      [ (k, test) | k <- [minBound .. maxBound]
      , let test = notP (Map.findWithDefault falseP k xs), test /= falseP ]
    ByKind xs >&< ByKind ys =
      ByKind (Map.filter (/= falseP) (Map.intersectionWith (>&<) xs ys))

-- | Test a token, tagged by its kind, by its kind's test of its tag.
testByKind :: Ord kind => (test -> tag -> Bool) -> ByKind kind test -> kind -> tag -> Bool
testByKind tested (ByKind xs) kind tag = maybe False (`tested` tag) (Map.lookup kind xs)

-- memo tries of tests, by their forms
instance HasTrie (TokenTest token) => HasTrie (TokenClass token) where
  newtype (TokenClass token :->: b) = TokenClassTrie (TokenTest token :->: b)
  trie f = TokenClassTrie (trie (f . TokenClass))
  untrie (TokenClassTrie t) (TokenClass test) = untrie t test
  enumerate (TokenClassTrie t) = first TokenClass <$> enumerate t
instance (Ord token, Enum token, HasTrie token) => HasTrie (TokenRanges token) where
  newtype (TokenRanges token :->: b) = TokenRangesTrie ([(token, token)] :->: b)
  trie f = TokenRangesTrie (trie (f . TokenRanges . RSet.fromRangeList))
  untrie (TokenRangesTrie t) (TokenRanges xs) = untrie t (RSet.toRangeList xs)
  enumerate (TokenRangesTrie t) = first (TokenRanges . RSet.fromRangeList) <$> enumerate t
instance (Ord token, HasTrie token) => HasTrie (Cofinite token) where
  newtype (Cofinite token :->: b) = CofiniteTrie (Either [token] [token] :->: b)
  trie f = CofiniteTrie (trie (f . either (Finite . Set.fromList) (Cofinite . Set.fromList)))
  untrie (CofiniteTrie t) = untrie t . \case
    Finite xs -> Left (Set.toList xs)
    Cofinite xs -> Right (Set.toList xs)
  enumerate (CofiniteTrie t) =
    first (either (Finite . Set.fromList) (Cofinite . Set.fromList)) <$> enumerate t
